// MarchingCubes — extract an isosurface from a sampled scalar field.
//
// Used by PlantSkinMeshBuilder to convert the bone-list SDF into a
// triangle mesh (single watertight surface). SSOT Phase 4 (Continuous
// PlantSkinMesh).
//
// Implementation: classic Marching Cubes (Lorensen & Cline 1987) with
// Paul Bourke's public-domain edge/triangle lookup tables.
// Reference: https://paulbourke.net/geometry/polygonise/
//
// Notes:
//   - vertex deduplication is omitted for simplicity (each cell emits
//     fresh vertices). This roughly triples vertex count vs an indexed
//     extractor. For plant meshes (≤200K vertices) this is fine; can
//     be optimized later if needed.
//   - Linear interpolation along voxel edges based on the SDF value.
//   - Normals can be computed downstream from positions+indices via
//     Babylon `VertexData.ComputeNormals`. We don't ship normals from
//     here to keep this module independent of Babylon.
//
// Pure math, zero dependencies.

import type { V3 } from './CapsuleSDF';

/** Scalar field sample function. Negative inside the surface. */
export type SDFFunction = (x: number, y: number, z: number) => number;

export interface IsosurfaceMesh {
  /** Flat [x0,y0,z0, x1,y1,z1, ...] positions, length = 3 * vertexCount. */
  positions: Float32Array;
  /** Flat triangle indices, length = 3 * triangleCount. Each consecutive
   *  triple references positions. */
  indices: Uint32Array;
  vertexCount: number;
  triangleCount: number;
}

export interface ExtractOptions {
  bounds: { min: V3; max: V3 };
  /** Cubic voxel size in same units as bounds (meters for FarmSim). */
  voxelSize: number;
  /** Isosurface value. SDFs use 0 for the surface. */
  isoValue?: number;
}

